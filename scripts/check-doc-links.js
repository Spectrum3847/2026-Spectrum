// Fails when a Markdown file links to a repo path that does not exist.
//
//   node scripts/check-doc-links.js
//
// Documentation drifting away from the code is the expensive kind of rot: a link to a class that
// was renamed sends a reader — or an AI assistant — hunting for a file that is not there, and a
// paragraph describing a dead architecture gets copied into new code. Broken links are the part of
// that we can catch mechanically, so we do.
//
// Checked: every relative link target in every tracked .md file. Skipped: URLs, bare anchors,
// mailto:, and BuildConstants.java (generated by the gversion plugin at build time, so it is
// legitimately absent from a clean checkout).
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const SKIP = [/^https?:/i, /^mailto:/i, /^#/];
const GENERATED = ["src/main/java/frc/robot/BuildConstants.java"];

const files = execFileSync("git", ["ls-files", "*.md"], { cwd: ROOT, encoding: "utf8" })
    .split("\n")
    .filter(Boolean)
    .filter((f) => !f.includes("node_modules/"));

const broken = [];
for (const file of files) {
    const dir = path.dirname(path.join(ROOT, file));
    const text = fs.readFileSync(path.join(ROOT, file), "utf8");
    // Markdown inline links: ](target) — strip any #anchor and any "title" suffix.
    for (const m of text.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
        const target = m[1].split("#")[0];
        if (!target || SKIP.some((re) => re.test(target))) continue;
        const resolved = path.resolve(dir, target);
        if (GENERATED.some((g) => resolved === path.join(ROOT, g))) continue;
        if (!fs.existsSync(resolved)) {
            const line = text.slice(0, m.index).split("\n").length;
            broken.push(`${file}:${line}  ->  ${target}`);
        }
    }
}

if (broken.length) {
    console.error(`${broken.length} broken link(s) in Markdown:\n`);
    for (const b of broken) console.error("  " + b);
    console.error("\nFix the link, or delete the sentence if what it pointed at is gone.");
    process.exit(1);
}
console.log(`Checked ${files.length} Markdown files; all relative links resolve.`);
